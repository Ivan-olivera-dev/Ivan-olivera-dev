import test from "node:test";
import assert from "node:assert/strict";
import { parsePgm, imageToAscii, glyphLevel, DEFAULT_RAMP } from "../src/portrait.ts";

function pgm(width: number, height: number, pixels: number[], header = `P5\n${width} ${height}\n255\n`): Uint8Array {
  return new Uint8Array([...Buffer.from(header, "latin1"), ...pixels]);
}

test("parsePgm reads a binary P5 image, skipping header comments", () => {
  const img = parsePgm(pgm(2, 2, [0, 64, 128, 255], "P5\n# generated by magick\n2 2\n255\n"));

  assert.equal(img.width, 2);
  assert.equal(img.height, 2);
  assert.deepEqual([...img.pixels], [0, 64, 128, 255]);
});

test("parsePgm rejects non-binary PGM input", () => {
  const ascii = new Uint8Array(Buffer.from("P2\n1 1\n255\n0\n", "latin1"));

  assert.throws(() => parsePgm(ascii), { message: "Unsupported PGM: expected binary P5 header" });
});

test("parsePgm rejects truncated pixel data", () => {
  assert.throws(() => parsePgm(pgm(2, 2, [0, 0, 0])), { message: "Truncated PGM: expected 4 pixels, got 3" });
});

test("imageToAscii turns the white background into blank space and dark pixels into dense glyphs", () => {
  const img = parsePgm(pgm(3, 2, [0, 255, 250, 120, 255, 0]));
  const rows = imageToAscii(img, { backgroundThreshold: 235 });

  assert.equal(rows.length, 2);
  assert.equal(rows[0], "@");
  assert.equal(rows[1][0], DEFAULT_RAMP[Math.floor((120 / 235) * (DEFAULT_RAMP.length - 1))]);
  assert.equal(rows[1], `${rows[1][0]} @`);
  assert.ok(!rows.some((row) => row.endsWith(" ")), "rows should not keep trailing background");
});

test("glyphLevel ranks glyphs from blank (0) to densest (1)", () => {
  assert.equal(glyphLevel(" "), 0);
  assert.equal(glyphLevel(DEFAULT_RAMP[0]), 1);
  assert.ok(glyphLevel("+") > glyphLevel("."), "denser glyphs rank higher");
  assert.equal(glyphLevel("?"), 0, "unknown glyphs are treated as blank");
});
